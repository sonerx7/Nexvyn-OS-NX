#!/usr/bin/env python3
"""Compile and validate vk_canary GLSL shaders to SPIR-V and emit embedded C arrays.

Uses host glslangValidator (or glslang) and spirv-val with --target-env vulkan1.3.
Never accesses the network. Replaces the output header atomically only after both
compilation and SPIR-V validation succeed.
"""
import argparse
import os
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import tempfile

SPIRV_MAGIC = 0x07230203
TARGET_ENV = "vulkan1.3"


def resolve_tool(explicit, env_names, candidates):
    if explicit:
        path = Path(explicit)
        if path.is_file():
            return str(path)
        found = shutil.which(explicit)
        if found:
            return found
        raise FileNotFoundError(f"Tool not found: {explicit}")
    for env_name in env_names:
        val = os.environ.get(env_name, "").strip()
        if not val:
            continue
        path = Path(val)
        if path.is_file():
            return str(path)
        found = shutil.which(val)
        if found:
            return found
    for name in candidates:
        found = shutil.which(name)
        if found:
            return found
    raise FileNotFoundError(f"Could not find any of {', '.join(candidates)} (set {'/'.join(env_names)})")


def bytes_to_spirv_words(data):
    if len(data) < 20 or len(data) % 4 != 0:
        raise ValueError(f"Invalid SPIR-V byte length: {len(data)}")
    words = struct.unpack(f"<{len(data) // 4}I", data)
    if words[0] != SPIRV_MAGIC:
        raise ValueError(f"Invalid SPIR-V magic: 0x{words[0]:08x}")
    return words


def format_c_array(symbol, words):
    lines = [f"static const uint32_t {symbol}[{len(words)}] = {{"]
    for i in range(0, len(words), 8):
        chunk = ", ".join(f"0x{w:08x}u" for w in words[i:i + 8])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def render_header(vert_words, frag_words):
    return (
        "/* Generated by vk_canary/tools/compile_shaders.py (--target-env vulkan1.3). */\n"
        "#ifndef VK_CANARY_SHADERS_H\n"
        "#define VK_CANARY_SHADERS_H\n\n"
        "#include <stdint.h>\n\n"
        + format_c_array("kVkCanaryVertSpv", vert_words)
        + "\n\n"
        + format_c_array("kVkCanaryFragSpv", frag_words)
        + "\n\n#endif /* VK_CANARY_SHADERS_H */\n"
    )


def compile_and_validate(glslang, spirv_val, source, output_spv):
    subprocess.run(
        [glslang, "-V", "--target-env", TARGET_ENV, str(source), "-o", str(output_spv)],
        check=True,
    )
    subprocess.run(
        [spirv_val, "--target-env", TARGET_ENV, str(output_spv)],
        check=True,
    )
    return bytes_to_spirv_words(output_spv.read_bytes())


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vert", required=True, type=Path)
    parser.add_argument("--frag", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--glslang", default="", help="Path to glslangValidator or glslang")
    parser.add_argument("--spirv-val", default="", help="Path to spirv-val")
    parser.add_argument("--spv-dir", type=Path, help="Optional directory to keep compiled .spv files")
    args = parser.parse_args(argv)

    vert = args.vert.resolve()
    frag = args.frag.resolve()
    out = args.out.resolve()
    if not vert.is_file():
        raise SystemExit(f"error: vertex shader not found: {vert}")
    if not frag.is_file():
        raise SystemExit(f"error: fragment shader not found: {frag}")

    try:
        glslang = resolve_tool(args.glslang, ("NEXVYN_GLSLANG", "GLSLANG_VALIDATOR"),
                               ("glslangValidator", "glslang"))
        spirv_val = resolve_tool(args.spirv_val, ("NEXVYN_SPIRV_VAL", "SPIRV_VAL"), ("spirv-val",))
    except FileNotFoundError as exc:
        raise SystemExit(f"error: {exc}")

    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".vk-canary-spv-", dir=out.parent) as tmp:
        tmp_dir = Path(tmp)
        vert_spv = tmp_dir / "triangle.vert.spv"
        frag_spv = tmp_dir / "triangle.frag.spv"
        vert_words = compile_and_validate(glslang, spirv_val, vert, vert_spv)
        frag_words = compile_and_validate(glslang, spirv_val, frag, frag_spv)
        header_text = render_header(vert_words, frag_words)
        candidate = tmp_dir / out.name
        candidate.write_text(header_text, encoding="ascii", newline="\n")
        if args.spv_dir:
            spv_dir = args.spv_dir.resolve()
            spv_dir.mkdir(parents=True, exist_ok=True)
            shutil.copy2(vert_spv, spv_dir / vert_spv.name)
            shutil.copy2(frag_spv, spv_dir / frag_spv.name)
        candidate.replace(out)
    print(f"generated {out} (vert={len(vert_words)} words, frag={len(frag_words)} words)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
