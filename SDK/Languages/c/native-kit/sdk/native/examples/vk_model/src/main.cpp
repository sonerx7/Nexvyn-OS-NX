static void log_line(nxn_log_level level, const char* line) {
    nxn_log_write(level, line);
    puts(line);
    fflush(stdout);
}

static const char* tr_or(const char* key, const char* fallback) {
    const char* text = nxn_tr(key);
    return (!text || !*text || strcmp(text, key) == 0) ? fallback : text;
}

/* Leave with a message Nexvyn OS shows to the user. */
static int fail_with_message(const char* key, const char* fallback, const char* log_reason) {
    char line[160];
    snprintf(line, sizeof(line), "VKMODEL: FAIL reason=%s", log_reason);
    log_line(NXN_LOG_ERROR, line);
    nxn_request_return(NXN_RETURN_ERROR, 1, tr_or(key, fallback));
    return 1;
}

