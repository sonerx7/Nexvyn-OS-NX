static int create_instance_and_surface(App* app) {
    PFN_nxn_vk_wsi_instance_extensions get_ext =
        (PFN_nxn_vk_wsi_instance_extensions)nxn_vk_proc("nxn_vk_wsi_instance_extensions");
    PFN_nxn_vk_wsi_create_surface create_surface =
        (PFN_nxn_vk_wsi_create_surface)nxn_vk_proc("nxn_vk_wsi_create_surface");
    if (!create_surface) return check(app, VK_ERROR_EXTENSION_NOT_PRESENT, "wsi_surface_hook_missing");

    const char* ext[16];
    uint32_t ext_count = 0;
    if (get_ext && get_ext(&ext_count, NULL) == VK_SUCCESS) {
        if (ext_count > 16u) ext_count = 16u;
        if (ext_count && get_ext(&ext_count, ext) < 0) ext_count = 0;
    }
    if (!ext_count) {
        ext[0] = VK_KHR_SURFACE_EXTENSION_NAME;
        ext_count = 1;
    }
    VkApplicationInfo ai = {};
    ai.sType = VK_STRUCTURE_TYPE_APPLICATION_INFO;
    ai.pApplicationName = "Nexvyn Vulkan Model";
    ai.applicationVersion = VK_MAKE_VERSION(1, 0, 0);
    ai.pEngineName = "NexvynNativeKit";
    ai.apiVersion = VK_API_VERSION_1_4; /* host image copy is core in 1.4; older devices use the 1.3 paths */
    VkInstanceCreateInfo ci = {};
    ci.sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO;
    ci.pApplicationInfo = &ai;
    ci.enabledExtensionCount = ext_count;
    ci.ppEnabledExtensionNames = ext;
    if (!check(app, vkCreateInstance(&ci, NULL, &app->instance), "create_instance")) return 0;
    return check(app, create_surface(app->instance, &app->surface), "create_surface");
}

static int has_swapchain_ext(VkPhysicalDevice gpu) {
    uint32_t n = 0;
    if (vkEnumerateDeviceExtensionProperties(gpu, NULL, &n, NULL) != VK_SUCCESS || !n) return 0;
    VkExtensionProperties* p = (VkExtensionProperties*)calloc(n, sizeof(*p));
    int found = 0;
    if (p && vkEnumerateDeviceExtensionProperties(gpu, NULL, &n, p) == VK_SUCCESS) {
        for (uint32_t i = 0; i < n && !found; ++i) found = strcmp(p[i].extensionName, VK_KHR_SWAPCHAIN_EXTENSION_NAME) == 0;
    }
    free(p);
    return found;
}

static int layout_listed(const VkImageLayout* list, uint32_t count, VkImageLayout layout);

static int create_device(App* app) {
    VkPhysicalDevice gpus[8];
    uint32_t n = 8;
    VkResult r = vkEnumeratePhysicalDevices(app->instance, &n, gpus);
    if (r < 0 || n == 0) return check(app, r < 0 ? r : VK_ERROR_INITIALIZATION_FAILED, "no_physical_device");
    for (uint32_t g = 0; g < n && !app->gpu; ++g) {
        if (!has_swapchain_ext(gpus[g])) continue;
        VkQueueFamilyProperties q[16];
        uint32_t qn = 16;
        vkGetPhysicalDeviceQueueFamilyProperties(gpus[g], &qn, q);
        for (uint32_t i = 0; i < qn; ++i) {
            VkBool32 present = VK_FALSE;
            if (vkGetPhysicalDeviceSurfaceSupportKHR(gpus[g], i, app->surface, &present) != VK_SUCCESS) continue;
            if ((q[i].queueFlags & VK_QUEUE_GRAPHICS_BIT) && present) {
                app->gpu = gpus[g];
                app->queue_family = i;
                break;
            }
        }
    }
    if (!app->gpu) return check(app, VK_ERROR_INITIALIZATION_FAILED, "no_graphics_present_queue");

    VkPhysicalDeviceProperties props;
    vkGetPhysicalDeviceProperties(app->gpu, &props);
    snprintf(app->gpu_name, sizeof(app->gpu_name), "%s", props.deviceName);
    snprintf(app->driver, sizeof(app->driver), "api %u.%u.%u driver 0x%08x", VK_API_VERSION_MAJOR(props.apiVersion),
             VK_API_VERSION_MINOR(props.apiVersion), VK_API_VERSION_PATCH(props.apiVersion), props.driverVersion);
    if (props.apiVersion >= VK_API_VERSION_1_2) {
        VkPhysicalDeviceDriverProperties drv = {};
        drv.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_DRIVER_PROPERTIES;
        VkPhysicalDeviceProperties2 p2 = {};
        p2.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2;
        p2.pNext = &drv;
        vkGetPhysicalDeviceProperties2(app->gpu, &p2);
        if (drv.driverName[0]) {
            snprintf(app->driver, sizeof(app->driver), "%s %s (api %u.%u)", drv.driverName, drv.driverInfo,
                     VK_API_VERSION_MAJOR(props.apiVersion), VK_API_VERSION_MINOR(props.apiVersion));
        }
    }
    vkGetPhysicalDeviceMemoryProperties(app->gpu, &app->mem_props);

    const float prio = 1.0f;
    VkDeviceQueueCreateInfo qi = {};
    qi.sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO;
    qi.queueFamilyIndex = app->queue_family;
    qi.queueCount = 1;
    qi.pQueuePriorities = &prio;
    /* Host image copy: textures are written by the CPU into optimal-tiled images, no GPU copy command. */
    VkPhysicalDeviceVulkan14Features f14 = {};
    f14.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_4_FEATURES;
    VkImageLayout host_layout = VK_IMAGE_LAYOUT_UNDEFINED;
    if (props.apiVersion >= VK_API_VERSION_1_4) {
        VkPhysicalDeviceFeatures2 f2 = {};
        f2.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2;
        f2.pNext = &f14;
        vkGetPhysicalDeviceFeatures2(app->gpu, &f2);
        VkFormatProperties3 fp3 = {};
        fp3.sType = VK_STRUCTURE_TYPE_FORMAT_PROPERTIES_3;
        VkFormatProperties2 fp2 = {};
        fp2.sType = VK_STRUCTURE_TYPE_FORMAT_PROPERTIES_2;
        fp2.pNext = &fp3;
        vkGetPhysicalDeviceFormatProperties2(app->gpu, VK_FORMAT_R8G8B8A8_UNORM, &fp2);
        if (f14.hostImageCopy && (fp3.optimalTilingFeatures & VK_FORMAT_FEATURE_2_HOST_IMAGE_TRANSFER_BIT)) {
            VkImageLayout src[16], dst[16];
            VkPhysicalDeviceHostImageCopyProperties hp = {};
            hp.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_HOST_IMAGE_COPY_PROPERTIES;
            hp.copySrcLayoutCount = 16;
            hp.pCopySrcLayouts = src;
            hp.copyDstLayoutCount = 16;
            hp.pCopyDstLayouts = dst;
            VkPhysicalDeviceProperties2 p2 = {};
            p2.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2;
            p2.pNext = &hp;
            vkGetPhysicalDeviceProperties2(app->gpu, &p2);
            const uint32_t n = hp.copyDstLayoutCount < 16u ? hp.copyDstLayoutCount : 16u;
            if (layout_listed(dst, n, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL)) {
                host_layout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
            } else if (layout_listed(dst, n, VK_IMAGE_LAYOUT_GENERAL)) {
                host_layout = VK_IMAGE_LAYOUT_GENERAL;
            }
        }
    }
    VkPhysicalDeviceVulkan14Features enable14 = {};
    enable14.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_4_FEATURES;
    enable14.hostImageCopy = host_layout != VK_IMAGE_LAYOUT_UNDEFINED ? VK_TRUE : VK_FALSE;

    const char* dev_ext[] = {VK_KHR_SWAPCHAIN_EXTENSION_NAME};
    VkDeviceCreateInfo di = {};
    di.sType = VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO;
    if (enable14.hostImageCopy) di.pNext = &enable14;
    di.queueCreateInfoCount = 1;
    di.pQueueCreateInfos = &qi;
    di.enabledExtensionCount = 1;
    di.ppEnabledExtensionNames = dev_ext;
    if (!check(app, vkCreateDevice(app->gpu, &di, NULL, &app->device), "create_device")) return 0;
    /* The host may not route every 1.4 entry point: resolve them, core name first, then the extension name. */
    if (host_layout != VK_IMAGE_LAYOUT_UNDEFINED) {
        app->host_transition = (PFN_vkTransitionImageLayout)vkGetDeviceProcAddr(app->device, "vkTransitionImageLayout");
        if (!app->host_transition)
            app->host_transition = (PFN_vkTransitionImageLayout)vkGetDeviceProcAddr(app->device, "vkTransitionImageLayoutEXT");
        app->host_copy = (PFN_vkCopyMemoryToImage)vkGetDeviceProcAddr(app->device, "vkCopyMemoryToImage");
        if (!app->host_copy) app->host_copy = (PFN_vkCopyMemoryToImage)vkGetDeviceProcAddr(app->device, "vkCopyMemoryToImageEXT");
        if (app->host_transition && app->host_copy) app->host_copy_layout = host_layout;
    }
    VkFormatProperties lin;
    vkGetPhysicalDeviceFormatProperties(app->gpu, VK_FORMAT_R8G8B8A8_UNORM, &lin);
    app->linear_textures = (lin.linearTilingFeatures & VK_FORMAT_FEATURE_SAMPLED_IMAGE_BIT) != 0;
    /* Bind vkDeviceWaitIdle now: the host resolves functions lazily and refuses new lookups once the app is
     * closing, which would make the final idle wait fail (see vk_canary). */
    (void)vkDeviceWaitIdle(app->device);
    /* Same for every teardown call: destroying VK_NULL_HANDLE is a valid no-op that binds the entry point now. */
    vkDestroyFramebuffer(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyImageView(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyImage(app->device, VK_NULL_HANDLE, NULL);
    vkFreeMemory(app->device, VK_NULL_HANDLE, NULL);
    vkDestroySemaphore(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyFence(app->device, VK_NULL_HANDLE, NULL);
    vkDestroySwapchainKHR(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyBuffer(app->device, VK_NULL_HANDLE, NULL);
    vkDestroySampler(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyPipeline(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyPipelineLayout(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyDescriptorSetLayout(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyDescriptorPool(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyRenderPass(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyPipelineCache(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyCommandPool(app->device, VK_NULL_HANDLE, NULL);
    vkDestroyShaderModule(app->device, VK_NULL_HANDLE, NULL);
    vkDestroySurfaceKHR(app->instance, VK_NULL_HANDLE, NULL);
    vkGetDeviceQueue(app->device, app->queue_family, 0, &app->queue);

    char line[400];
    snprintf(line, sizeof(line), "VKMODEL: gpu=\"%s\" driver=\"%s\"", app->gpu_name, app->driver);
    log_line(NXN_LOG_INFO, line);
    return 1;
}

