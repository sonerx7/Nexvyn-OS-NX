static int check(App* app, VkResult r, const char* step) {
    if (r == VK_SUCCESS) return 1;
    if (!app->fail[0]) {
        snprintf(app->fail, sizeof(app->fail), "%s", step);
        app->fail_result = r;
    }
    return 0;
}

static uint32_t find_memory(const App* app, uint32_t type_bits, VkMemoryPropertyFlags want) {
    for (uint32_t i = 0; i < app->mem_props.memoryTypeCount; ++i) {
        if ((type_bits & (1u << i)) && (app->mem_props.memoryTypes[i].propertyFlags & want) == want) return i;
    }
    return UINT32_MAX;
}

static VkResult create_buffer(App* app, VkDeviceSize size, VkBufferUsageFlags usage, VkMemoryPropertyFlags props,
                              VkBuffer* buffer, VkDeviceMemory* memory) {
    VkBufferCreateInfo info = {};
    info.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
    info.size = size;
    info.usage = usage;
    info.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    VkResult r = vkCreateBuffer(app->device, &info, NULL, buffer);
    if (r != VK_SUCCESS) return r;
    VkMemoryRequirements req;
    vkGetBufferMemoryRequirements(app->device, *buffer, &req);
    VkMemoryAllocateInfo alloc = {};
    alloc.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    alloc.allocationSize = req.size;
    alloc.memoryTypeIndex = find_memory(app, req.memoryTypeBits, props);
    if (alloc.memoryTypeIndex == UINT32_MAX) return VK_ERROR_OUT_OF_DEVICE_MEMORY;
    r = vkAllocateMemory(app->device, &alloc, NULL, memory);
    if (r != VK_SUCCESS) return r;
    return vkBindBufferMemory(app->device, *buffer, *memory, 0);
}

static VkResult create_image(App* app, uint32_t w, uint32_t h, uint32_t mips, VkFormat format, VkImageUsageFlags usage,
                             VkImageAspectFlags aspect, GpuImage* out) {
    VkImageCreateInfo info = {};
    info.sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO;
    info.imageType = VK_IMAGE_TYPE_2D;
    info.format = format;
    info.extent.width = w;
    info.extent.height = h;
    info.extent.depth = 1;
    info.mipLevels = mips;
    info.arrayLayers = 1;
    info.samples = VK_SAMPLE_COUNT_1_BIT;
    info.tiling = VK_IMAGE_TILING_OPTIMAL;
    info.usage = usage;
    info.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    info.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    VkResult r = vkCreateImage(app->device, &info, NULL, &out->image);
    if (r != VK_SUCCESS) return r;
    VkMemoryRequirements req;
    vkGetImageMemoryRequirements(app->device, out->image, &req);
    VkMemoryAllocateInfo alloc = {};
    alloc.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    alloc.allocationSize = req.size;
    alloc.memoryTypeIndex = find_memory(app, req.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    if (alloc.memoryTypeIndex == UINT32_MAX) alloc.memoryTypeIndex = find_memory(app, req.memoryTypeBits, 0);
    r = vkAllocateMemory(app->device, &alloc, NULL, &out->memory);
    if (r != VK_SUCCESS) return r;
    r = vkBindImageMemory(app->device, out->image, out->memory, 0);
    if (r != VK_SUCCESS) return r;
    VkImageViewCreateInfo view = {};
    view.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
    view.image = out->image;
    view.viewType = VK_IMAGE_VIEW_TYPE_2D;
    view.format = format;
    view.subresourceRange.aspectMask = aspect;
    view.subresourceRange.levelCount = mips;
    view.subresourceRange.layerCount = 1;
    return vkCreateImageView(app->device, &view, NULL, &out->view);
}

static void destroy_image(App* app, GpuImage* img) {
    if (img->view) vkDestroyImageView(app->device, img->view, NULL);
    if (img->image) vkDestroyImage(app->device, img->image, NULL);
    if (img->memory) vkFreeMemory(app->device, img->memory, NULL);
    memset(img, 0, sizeof(*img));
}

