-- PBR, Lights and Shadows (SDK sample; also the Studio template "3D: PBR, Lights and Shadows")
-- Modern rendering with the "pbr" renderer (SDK 1.9): metallic-roughness materials, real-time lights, shadows, HDR
-- with tone mapping and bloom, and GPU instancing. The renderer is opt-in: g3d.renderer("pbr") returns "pbr" when the
-- console's GPU offers it and "basic" otherwise (then the same calls draw with the classic renderer; lights, shadows
-- and post effects are simply not shown).
--
-- models/crate.glb  a crate whose material has base color, normal, metallic-roughness and emissive maps
--                   (generated by a script in a 3D tool; CC0)
--
-- Renderer settings belong to the app: set them once (app.load) and change them when you need to. Lights have ids
-- (g3d.addLight returns one) and move with g3d.updateLight.

local app = {}

local crate, ground, pillar, bulbWarm, bulbCool
local spheres = {}
local pillars = {}   -- instance transforms for g3d.drawInstanced: x, y, z, rx, ry, rz, scale per pillar
local warm, cool, spot
local wantPbr, shadowsOn, bloomOn = true, true, true
local active = "basic"
local t = 0

local function applySettings()
    active = g3d.renderer(wantPbr and "pbr" or "basic")
    g3d.shadows({enabled = shadowsOn, quality = "medium", distance = 26})
    g3d.postfx({exposure = 1.0, tonemap = "aces", bloom = bloomOn and 0.08 or 0, threshold = 1.0})
    g3d.environment({sky = "#9DB8E8", ground = "#4A4038", intensity = 1.0, sun = 2.6})
end

function app.load(arg)
    crate = g3d.model("bundle:/models/crate.glb", 1.4)
    ground = g3d.mesh("plane", 40, 40, 1)
    ground:setColor("#6F757C")
    g3d.material(ground, {metallic = 0, roughness = 0.85})
    -- left to right: metallic 0 -> 1, roughness 0.15 -> 0.87
    for i = 1, 5 do
        local s = g3d.mesh("sphere", 0.45, 40, 28)
        s:setColor(i <= 2 and "#D9A441" or "#C8CCD2")
        g3d.material(s, {metallic = (i - 1) / 4, roughness = 0.15 + (i - 1) * 0.18})
        spheres[i] = s
    end
    pillar = g3d.mesh("box", 0.35, 2.2, 0.35)
    pillar:setColor("#B9B2A6")
    g3d.material(pillar, {roughness = 0.55})
    for i = 0, 23 do
        local a = i / 24 * math.pi * 2
        for _, v in ipairs({math.cos(a) * 9, 1.1, math.sin(a) * 9, 0, -a, 0, 1}) do pillars[#pillars + 1] = v end
    end
    -- small glowing bulbs where the point lights are: emission brighter than 1 feeds the bloom
    bulbWarm = g3d.mesh("sphere", 0.09, 16, 10)
    bulbWarm:setColor("#FF9A3C")
    g3d.material(bulbWarm, {emissive = "#FF9A3C", emissiveStrength = 8})
    bulbCool = g3d.mesh("sphere", 0.09, 16, 10)
    bulbCool:setColor("#3CC8FF")
    g3d.material(bulbCool, {emissive = "#3CC8FF", emissiveStrength = 8})

    warm = g3d.addLight({type = "point", color = "#FF9A3C", intensity = 6, range = 8})
    cool = g3d.addLight({type = "point", color = "#3CC8FF", intensity = 6, range = 8})
    spot = g3d.addLight({type = "spot", x = 0, y = 6, z = 0, dx = 0, dy = -1, dz = 0, color = "#FFFFFF",
                         intensity = 40, range = 14, inner = 12, outer = 20, shadow = true})
    applySettings()
end

local function warmPos() return math.cos(t * 0.9) * 3.2, 1.2 + math.sin(t * 1.7) * 0.4, math.sin(t * 0.9) * 3.2 end
local function coolPos() return math.cos(t * 0.7 + 3) * 2.6, 0.9, math.sin(t * 0.7 + 3) * 2.6 end

function app.update(dt)
    t = t + dt
    local x, y, z = warmPos()
    g3d.updateLight(warm, {x = x, y = y, z = z})
    x, y, z = coolPos()
    g3d.updateLight(cool, {x = x, y = y, z = z})
    g3d.updateLight(spot, {dx = math.sin(t * 0.5) * 0.45, dy = -1, dz = math.cos(t * 0.37) * 0.45})
end

function app.draw(w, h)
    local bg = "#0E1116"
    gfx.clear(bg)
    g3d.begin(0, 0, w, h - 52, 55, 0.1, 120)
    g3d.camera(math.sin(t * 0.15) * 11, 4.2, math.cos(t * 0.15) * 11, 0, 0.8, 0)
    g3d.light(0.45, 0.8, 0.35, 0.35, "#FFF1DD")   -- the sun (direction to it, ambient, color)
    g3d.fog(bg, 30, 70)
    g3d.draw(ground, 0, 0, 0)
    for i, s in ipairs(spheres) do g3d.draw(s, (i - 3) * 1.25, 0.45, -2.2) end
    if crate then
        g3d.draw(crate, -2.2, 0, 1.6, 0, t * 0.4, 0)
        g3d.draw(crate, 2.4, 0, 1.2, 0, -0.5, 0)
    end
    g3d.drawInstanced(pillar, pillars)            -- 24 pillars, one GPU call on the pbr renderer
    local x, y, z = warmPos()
    g3d.draw(bulbWarm, x, y, z, 0, 0, 0, 1, 1, 1, nil, active == "pbr" and "" or "unlit")
    x, y, z = coolPos()
    g3d.draw(bulbCool, x, y, z, 0, 0, 0, 1, 1, 1, nil, active == "pbr" and "" or "unlit")
    local tris = g3d.finish()

    gfx.rect(0, h - 52, w, 52, 0, theme.window)
    ui.separator(0, h - 52, w)
    gfx.color(theme.text2)
    gfx.text(TR("renderer", active), 16, h - 42, 13)
    gfx.text(TR("stats", tris, math.floor(sys.fps() + 0.5)), 16, h - 24, 13)
    if ui.button(TR(wantPbr and "basic" or "pbr"), w - 384, h - 42, 120, 32, "primary") then
        wantPbr = not wantPbr
        applySettings()
    end
    if ui.button(TR(shadowsOn and "shadowsOff" or "shadowsOn"), w - 256, h - 42, 120, 32) then
        shadowsOn = not shadowsOn
        applySettings()
    end
    if ui.button(TR(bloomOn and "bloomOff" or "bloomOn"), w - 128, h - 42, 112, 32) then
        bloomOn = not bloomOn
        applySettings()
    end
end

return app
