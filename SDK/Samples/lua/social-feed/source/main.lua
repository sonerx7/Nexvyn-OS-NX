-- Social Feed: a photo feed, a photo grid and a vertical video pager built on the SDK 1.9 functions
-- (sdk/SDK.en.md section 8d, guide: SDK/Guides/MAKE_A_SOCIAL_APP.en.md).
--   net.request   the feed as JSON, cached for 10 minutes, retried, with the bundled copy as the offline fallback
--   gfx.imageUrl  photos from the web (disk + memory cache, thumbnails); the bundled files when offline
--   ui.beginFeed  virtualized list and grid with pull-to-refresh and infinite scroll
--   ui.pager      full-screen vertical swipe between clips, media.* players (current + next one open)
--   ui.richText   captions with **bold**, links, @mentions and #hashtags; sys.relativeTime for "5m"
-- Media: generated by make_social_media.py, CC0 1.0.
local app = {}

local REMOTE = "https://raw.githubusercontent.com/sonerx7/Nexvyn-OS-NX/main/SDK/Samples/lua/social-feed/source/media/"
local TOP = 56

local tab, lastTab = 1, 1
local base, clips = {}, {}      -- the posts and clips of feed.json
local posts, pages = {}, 0      -- what the feed shows (pages of 12)
local heights, heightsW = {}, 0 -- measured post heights for the width heightsW
local refreshing, loadingMore = true, false
local remote = false            -- the web copy answered: pictures come from the web (cached)
local liked = {}
local status, statusT = "", 0
local players = {}              -- reel page -> media player id
local muted = false
local reelPage = 1

local function say(text) status, statusT = text, 3 end

-- ---------------------------------------------------------------- data
local function makePage(n)
  -- page n of the feed: the 12 posts of feed.json again with older times (a real server sends new posts)
  local out = {}
  for i, p in ipairs(base) do
    out[#out + 1] = {id = (n - 1) * 12 + i, user = p.user, photo = p.photo, caption = p.caption,
                     likes = p.likes + n * 3, time = sys.epoch() - 60 * (p.minutesAgo + (n - 1) * 720)}
  end
  return out
end

local function loadFeed(done)
  net.request({url = REMOTE .. "feed.json", responseType = "json", cache = 600, retry = 2, timeout = 15}, function(res)
    local data = res.ok and res.data or nil
    remote = data ~= nil and type(data.posts) == "table"
    if not remote then data = json.decode(fs.read("bundle:/media/feed.json") or "{}") or {} end
    base, clips = data.posts or {}, data.clips or {}
    if res.stale then say(TR("offline")) end
    done()
  end)
end

local function refresh()
  refreshing = true
  loadFeed(function()
    posts, pages, heights = makePage(1), 1, {}
    refreshing = false
  end)
end

local function loadMore()
  if pages >= 40 then return end
  loadingMore = true
  timer.after(0.6, function()  -- a server round trip
    pages = pages + 1
    for _, p in ipairs(makePage(pages)) do posts[#posts + 1] = p end
    loadingMore = false
  end)
end

local function photoOf(post, size)
  if remote then
    local img = gfx.imageUrl(REMOTE .. post.photo, size)
    if img then return img end
  end
  return gfx.image("bundle:/media/" .. post.photo)
end

-- ---------------------------------------------------------------- feed
local function postHeight(post, w)
  local photo = math.min(w - 24, 440)
  return 56 + photo + 48 + ui.measureRichText(post.caption, w - 24, 15) + 16
end

local function drawPost(post, x, y, w, h)
  gfx.rect(x + 8, y, w - 16, h, 14, theme.window)
  -- header: avatar, name, time
  gfx.circle(x + 36, y + 28, 16, theme.accent)
  gfx.color("#FFFFFF")
  gfx.text(post.user:sub(1, 1):upper(), x + 20, y + 18, 16, "bold", "center", 32)
  gfx.color(theme.text)
  gfx.text(post.user, x + 60, y + 12, 15, "semibold")
  gfx.color(theme.text2)
  gfx.text(sys.relativeTime(post.time), x + 60, y + 31, 12)
  -- photo (a thumbnail of the right size; a placeholder while it loads)
  local pw = math.min(w - 24, 440)
  local px, py = x + (w - pw) / 2, y + 56
  local img = photoOf(post, 640)
  if img then gfx.draw(img, px, py, pw, pw, 10) else gfx.rect(px, py, pw, pw, 10, theme.control) end
  -- actions
  local ay = py + pw + 6
  local on = liked[post.id]
  if ui.iconButton(on and "favorite" or "favorite_border", x + 14, ay, 36, 36, on and theme.red or theme.text, false, "like" .. post.id) then
    liked[post.id] = not on or nil
    store.set("liked", liked)
  end
  if ui.iconButton("share", x + 54, ay, 36, 36, theme.text, false, "share" .. post.id) then
    sys.share(post.caption .. " " .. sys.appUrl(sys.appid(), "post:" .. post.id))
  end
  gfx.color(theme.text2)
  gfx.text(TR("likes", post.likes + (on and 1 or 0)), x + 100, ay + 10, 13)
  -- caption
  gfx.color(theme.text)
  local r = ui.richText("cap" .. post.id, post.caption, x + 12, ay + 42, w - 24, 15)
  if r.clicked then
    local c = r.clicked
    say(c.type == "hashtag" and ("#" .. c.value) or c.type == "mention" and ("@" .. c.value) or c.value)
  end
end

local function drawFeed(x, y, w, h)
  if heightsW ~= w then heights, heightsW = {}, w end
  for i = #heights + 1, #posts do heights[i] = postHeight(posts[i], w) end
  local f = ui.beginFeed("feed", x, y, w, h, #posts, {heights = heights, gap = 10, padTop = 8, padBottom = 8,
                                                      refreshing = refreshing, loadingMore = loadingMore})
  for i = f.first, f.last do
    local r = ui.feedItem(i)
    drawPost(posts[i], r.x, r.y, r.w, r.h)
  end
  local ev = ui.endFeed()
  if ev.refresh then refresh() end
  if ev.more then loadMore() end
end

local function drawGrid(x, y, w, h)
  local f = ui.beginFeed("grid", x, y, w, h, #posts, {columns = w > 700 and 4 or 3, gap = 2,
                                                      refreshing = refreshing, loadingMore = loadingMore})
  for i = f.first, f.last do
    local r = ui.feedItem(i)
    local img = photoOf(posts[i], 256)
    if img then gfx.draw(img, r.x, r.y, r.w, r.h) else gfx.rect(r.x, r.y, r.w, r.h, 0, theme.control) end
  end
  local ev = ui.endFeed()
  if ev.refresh then refresh() end
  if ev.more then loadMore() end
end

-- ---------------------------------------------------------------- reels
local function clipOf(page) return clips[(page - 1) % #clips + 1] end

-- players for the current and the next page only (at most 3 per app); the current one plays
local function syncPlayers(page, count)
  for p, id in pairs(players) do
    if p ~= page and p ~= page + 1 then
      media.close(id)
      players[p] = nil
    end
  end
  for p = page, math.min(page + 1, count) do
    if not players[p] then players[p] = media.open("bundle:/media/" .. clipOf(p), {loop = true, muted = muted, autoplay = false}) end
  end
  for p, id in pairs(players) do
    if p == page and tab == 3 then media.play(id) else media.pause(id) end
  end
end

local function pauseAll()
  for _, id in pairs(players) do media.pause(id) end
end

local function drawReels(x, y, w, h)
  if #clips == 0 then return end
  local count = #clips * 4
  gfx.clip(x, y, w, h)
  gfx.rect(x, y, w, h, 0, "#000000")
  local pg = ui.pager("reels", x, y, w, h, count)
  if pg.changed or not players[pg.page] then
    reelPage = pg.page
    syncPlayers(pg.page, count)
  end
  local first = math.max(1, math.floor(pg.pos))
  for i = first, math.min(count, first + 1) do
    local py = y + (i - pg.pos) * h
    if players[i] then media.draw(players[i], x, py, w, h, "contain") end
    gfx.color("#FFFFFF")
    gfx.text(TR("clip", i), x + 20, py + h - 64, 18, "bold")
    gfx.color("#FFFFFFB0")
    gfx.text(TR("swipe"), x + 20, py + h - 38, 13)
  end
  local info = players[pg.page] and media.info(players[pg.page])
  if info and (info.state == "opening" or info.buffering) then ui.spinner(x + w / 2, y + h / 2, 18) end
  if info and info.state == "failed" then
    gfx.color("#FFFFFF")
    gfx.text(info.error, x, y + h / 2, 14, "sans", "center", w)
  end
  if ui.iconButton(muted and "volume_off" or "volume_up", x + w - 56, y + 12, 44, 44, "#FFFFFF", false, "mute") then
    muted = not muted
    for _, id in pairs(players) do media.set(id, {muted = muted}) end
  end
  gfx.unclip()
end

-- ---------------------------------------------------------------- app
function app.load(arg)
  liked = store.get("liked", {})
  refresh()
  if type(arg) == "string" and arg:sub(1, 5) == "post:" then say(TR("opened", arg:sub(6))) end
end

function app.open(arg)
  if type(arg) == "string" and arg:sub(1, 5) == "post:" then
    tab = 1
    say(TR("opened", arg:sub(6)))
  end
end

function app.update(dt)
  if statusT > 0 then statusT = statusT - dt end
end

function app.draw(w, h)
  gfx.clear(theme.bg)
  tab = ui.segmented("tabs", {TR("feed"), TR("grid"), TR("reels")}, tab, 12, 12, math.min(420, w - 24), 32)
  if tab ~= lastTab then
    if lastTab == 3 then pauseAll() end
    if tab == 3 then syncPlayers(reelPage, #clips * 4) end
    lastTab = tab
  end
  if tab == 1 then drawFeed(0, TOP, w, h - TOP)
  elseif tab == 2 then drawGrid(0, TOP, w, h - TOP)
  else drawReels(0, TOP, w, h - TOP) end
  if statusT > 0 and status ~= "" then
    local tw = math.min(w - 40, gfx.textWidth(status, 14) + 32)
    gfx.rect((w - tw) / 2, h - 56, tw, 36, 18, "#000000C0")
    gfx.color("#FFFFFF")
    gfx.text(status, (w - tw) / 2, h - 47, 14, "sans", "center", tw)
  end
end

function app.suspend() pauseAll() end

function app.resume()
  if tab == 3 and players[reelPage] then media.play(players[reelPage]) end
end

function app.close()
  for _, id in pairs(players) do media.close(id) end
  return true
end

return app
